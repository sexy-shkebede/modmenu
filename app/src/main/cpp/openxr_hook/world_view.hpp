#pragma once

// Один глаз для слоя мира: поза и поле зрения — из проекционного слоя самой игры
// (её пространство, OpenXR: -Z вперёд), участок текстуры слоя — в пикселях.
// Простые float, чтобы рисующему коду не тянуть заголовки OpenXR.
struct SWorldEye
{
    float aPos[3];
    float aRot[4];                    // кватернион x, y, z, w
    float fTanL, fTanR, fTanU, fTanD; // тангенсы углов поля зрения (лево и низ отрицательные)
    float fX, fY, fW, fH;
};
